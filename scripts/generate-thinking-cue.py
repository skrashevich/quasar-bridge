#!/usr/bin/env python3
"""Generate original two-tone Opus packets offline. No encoder is used at runtime.
Use Ubuntu libopus0 1.4-1build1 (deb SHA256
6d8da32a832e655c9603543b47a0bc90c6f60bdee0c00fe7499bd50acad566cf).
Pass the extracted libopus.so.0 path and output Go file as arguments.
"""
import ctypes as C
import math
from pathlib import Path
import sys

lib = C.CDLL(sys.argv[1])
lib.opus_encoder_create.argtypes = [C.c_int32,C.c_int,C.c_int,C.POINTER(C.c_int)]
lib.opus_encoder_create.restype = C.c_void_p
lib.opus_encoder_ctl.argtypes = [C.c_void_p,C.c_int,C.c_int]
lib.opus_encode.argtypes = [C.c_void_p,C.POINTER(C.c_int16),C.c_int,C.POINTER(C.c_ubyte),C.c_int32]
lib.opus_encoder_destroy.argtypes = [C.c_void_p]
error=C.c_int()
encoder=lib.opus_encoder_create(48000,1,2051,C.byref(error))
assert encoder and error.value == 0
assert lib.opus_encoder_ctl(encoder,4002,24000) == 0
packets=[]
for frame in range(20):
    pcm=(C.c_int16*960)()
    for i in range(960):
        t=(frame*960+i)/48000
        for start,freq in [(0.06,660),(0.22,880)]:
            pos=t-start
            if 0 <= pos < 0.1:
                envelope=min(1,pos/0.01,(0.1-pos)/0.01)
                pcm[i]=round(32767*0.12*envelope*math.sin(2*math.pi*freq*pos))
    output=(C.c_ubyte*4000)()
    n=lib.opus_encode(encoder,pcm,960,output,4000)
    assert n > 0
    packets.append(bytes(output[:n]))
lib.opus_encoder_destroy(encoder)
lines=['// Code generated by scripts/generate-thinking-cue.py; DO NOT EDIT.',
       '// Original 660/880 Hz tones, 400ms including silence, peak about -18 dBFS.',
       'package bridge','','var thinkingCuePackets = [][]byte{']
for packet in packets:
    lines.append('\t{'+', '.join(f'0x{b:02x}' for b in packet)+'},')
lines.append('}')
Path(sys.argv[2]).write_text('\n'.join(lines)+'\n')
print(f'Generated {len(packets)} packets, {sum(map(len,packets))} bytes.')
